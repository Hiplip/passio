import { TRPCError } from "@trpc/server";
import { and, asc, eq } from "drizzle-orm";
import { z } from "zod";

import { createTRPCRouter, protectedProcedure } from "~/server/api/trpc";
import { folder } from "~/server/db/schema";

/**
 * The server cannot read the contents, but it can insist on the envelope shape
 * so a malformed blob never reaches storage: a version tag, the base64url IV
 * and the base64url payload.
 *
 * A folder's name is as much a secret as an item's password — "Crypto wallets"
 * leaks intent on its own — so it arrives sealed, exactly like an item.
 */
const ciphertext = z
  .string()
  .regex(/^v1\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/, "malformed ciphertext");

/**
 * Folder ids are generated by the client, because a folder's ciphertext is
 * bound to its id as AES-GCM additional authenticated data (`folderAad`): the
 * id has to exist before the plaintext can be sealed. A client-chosen id is not
 * a client-chosen row — every statement below is scoped to the caller in its
 * WHERE clause, and `create` refuses an id that is already taken rather than
 * writing over it.
 */
const folderId = z.string().uuid();

export const folderRouter = createTRPCRouter({
  /**
   * Oldest first. The sidebar renders this order directly, and `createdAt`
   * never moves, so renaming a folder does not make the list reshuffle under
   * the user's cursor.
   */
  list: protectedProcedure.query(async ({ ctx }) => {
    return ctx.db
      .select({
        id: folder.id,
        ciphertext: folder.ciphertext,
        createdAt: folder.createdAt,
        updatedAt: folder.updatedAt,
      })
      .from(folder)
      .where(eq(folder.userId, ctx.session.user.id))
      .orderBy(asc(folder.createdAt), asc(folder.id));
  }),

  create: protectedProcedure
    .input(z.object({ id: folderId, ciphertext }))
    .mutation(async ({ ctx, input }) => {
      const now = new Date();

      // `onConflictDoNothing` is what keeps a guessed id harmless: a collision
      // writes nothing and returns nothing, whoever owns the existing row. The
      // response is the same CONFLICT either way, so it never tells the caller
      // that the id belongs to somebody else.
      const [created] = await ctx.db
        .insert(folder)
        .values({
          id: input.id,
          userId: ctx.session.user.id,
          ciphertext: input.ciphertext,
          createdAt: now,
          updatedAt: now,
        })
        .onConflictDoNothing({ target: folder.id })
        .returning({ id: folder.id });

      if (!created) {
        throw new TRPCError({ code: "CONFLICT", message: "id already in use" });
      }
      return created;
    }),

  /** Renaming a folder is just replacing its ciphertext; the id, and therefore
   * the AAD the items were sealed against, stays put. */
  rename: protectedProcedure
    .input(z.object({ id: folderId, ciphertext }))
    .mutation(async ({ ctx, input }) => {
      // Ownership lives in the WHERE clause. Another user's row is
      // indistinguishable from a row that does not exist.
      const [renamed] = await ctx.db
        .update(folder)
        .set({ ciphertext: input.ciphertext, updatedAt: new Date() })
        .where(
          and(eq(folder.id, input.id), eq(folder.userId, ctx.session.user.id)),
        )
        .returning({ id: folder.id, updatedAt: folder.updatedAt });

      if (!renamed) throw new TRPCError({ code: "NOT_FOUND" });
      return renamed;
    }),

  /**
   * Hard delete. Folders have no soft delete: a folder holds no secret but its
   * own name, and the items it grouped are untouched, so a mis-click costs a
   * name rather than data.
   *
   * There is deliberately no cascade here. An item records its folder inside
   * its own encrypted blob, so the server cannot tell which items pointed at
   * this folder and could not update them without a key it must never have.
   * Items whose blob names a deleted folder simply read as unfiled, and the
   * client handles that. The missing cascade is the design, not an oversight.
   */
  delete: protectedProcedure
    .input(z.object({ id: folderId }))
    .mutation(async ({ ctx, input }) => {
      const [deleted] = await ctx.db
        .delete(folder)
        .where(
          and(eq(folder.id, input.id), eq(folder.userId, ctx.session.user.id)),
        )
        .returning({ id: folder.id });

      if (!deleted) throw new TRPCError({ code: "NOT_FOUND" });
      return deleted;
    }),
});
