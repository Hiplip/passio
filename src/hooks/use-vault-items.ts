"use client";

import { useEffect, useState } from "react";

import { encryptItem, itemAad, type VaultKey } from "@passio/crypto";
import {
  decryptVault,
  type DecryptedItem,
  type DecryptedVault,
} from "@passio/core/decrypt-vault";
import type { Item } from "@passio/core/schema";
import { api } from "~/trpc/react";

const EMPTY: DecryptedVault = { items: [], damaged: [] };

/**
 * Fetches the vault and decrypts it in memory.
 *
 * Decryption runs in an effect rather than during render because it is async;
 * the rows are ciphertext until it completes, so the list renders as loading
 * rather than briefly empty, which would read as data loss.
 */
export function useVaultItems(
  vaultKey: VaultKey | null,
  options: { deleted?: boolean; enabled?: boolean } = {},
) {
  const wantsDeleted = options.deleted === true;
  const active = (options.enabled ?? true) && vaultKey !== null;

  const live = api.item.list.useQuery(undefined, {
    enabled: active && !wantsDeleted,
  });
  const trashed = api.item.listDeleted.useQuery(undefined, {
    enabled: active && wantsDeleted,
  });
  // Selected by what the caller asked for, never by which query happens to
  // have data: reading the live list while asking for trash is how the trash
  // count ended up showing the live item count.
  const rows = wantsDeleted ? trashed : live;
  const [vault, setVault] = useState<DecryptedVault>(EMPTY);
  const [decrypting, setDecrypting] = useState(true);

  useEffect(() => {
    if (!vaultKey || !rows.data) {
      setVault(EMPTY);
      return;
    }

    let cancelled = false;
    setDecrypting(true);

    void decryptVault(rows.data, vaultKey).then((next) => {
      if (cancelled) return;
      setVault(next);
      setDecrypting(false);
    });

    return () => {
      cancelled = true;
    };
  }, [rows.data, vaultKey]);

  return {
    ...vault,
    isLoading: rows.isPending || decrypting,
    error: rows.error,
  };
}

/**
 * Encrypts an item for storage.
 *
 * The id is generated by the caller before encryption, because the id is the
 * additional authenticated data - the ciphertext is bound to the row it belongs
 * to, so it cannot be moved to another row undetected.
 */
export async function encryptForStorage(
  id: string,
  item: Item,
  vaultKey: VaultKey,
): Promise<string> {
  return encryptItem(item, vaultKey, itemAad(id));
}

export type { DecryptedItem };
