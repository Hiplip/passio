"use client";

import { useEffect, useState } from "react";

import { encryptItem, folderAad, type VaultKey } from "@passio/crypto";
import {
  decryptFolders,
  type DecryptedFolder,
} from "@passio/core/decrypt-folders";
import { api } from "~/trpc/react";

/** Fetches the folder list and decrypts it in memory. */
export function useFolders(vaultKey: VaultKey | null) {
  const rows = api.folder.list.useQuery(undefined, { enabled: vaultKey !== null });
  const [folders, setFolders] = useState<DecryptedFolder[]>([]);
  const [decrypting, setDecrypting] = useState(true);

  useEffect(() => {
    if (!vaultKey || !rows.data) {
      setFolders([]);
      return;
    }

    let cancelled = false;
    setDecrypting(true);

    void decryptFolders(rows.data, vaultKey).then((next) => {
      if (cancelled) return;
      setFolders(next);
      setDecrypting(false);
    });

    return () => {
      cancelled = true;
    };
  }, [rows.data, vaultKey]);

  return { folders, isLoading: rows.isPending || decrypting };
}

/**
 * Encrypts a folder name for storage.
 *
 * The id is generated by the caller before encryption, because the id is the
 * additional authenticated data - the same rule items follow.
 */
export async function encryptFolderName(
  id: string,
  name: string,
  vaultKey: VaultKey,
): Promise<string> {
  return encryptItem({ name }, vaultKey, folderAad(id));
}

export type { DecryptedFolder };
